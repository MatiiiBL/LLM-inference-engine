#!/usr/bin/env python3
"""Generates unicode_tables.h: the \\p{L} and \\p{N} code point ranges.

The tokenizer needs exactly two Unicode properties that are too large to write
by hand:

  * \\p{L} (Lu Ll Lt Lm Lo) and \\p{N} (Nd Nl No) for the GPT-2 pre-tokenizer
    regex, which tokenizers runs through Oniguruma;
  * Rust's char::is_numeric (also Nd Nl No) for the Digits pre-tokenizer.

Whitespace (\\s, i.e. the White_Space property) is ten ranges and lives in
tokenizer.cpp directly.

The tables follow this interpreter's unicodedata version, which is recorded in
the generated header. It must match the Unicode version of the tokenizers
build being reproduced — 16.0 for tokenizers 0.23 (its Rust std and its
Oniguruma agree on it) — or code points assigned in between classify
differently. (Its Rust std is one version further, on 17.0; the 13 numbers
17.0 added are listed by hand in tokenizer.cpp's is_numeric.) Python 3.14
ships 16.0:

    python3.14 src/tokenizer/gen_unicode_tables.py > src/tokenizer/unicode_tables.h
"""

import sys
import unicodedata


def ranges(categories: set[str]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in range(sys.maxunicode + 1):
        if unicodedata.category(chr(cp)) not in categories:
            continue
        if out and out[-1][1] == cp - 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def emit(name: str, rs: list[tuple[int, int]]) -> None:
    print(f"inline constexpr CodePointRange {name}[] = {{")
    for lo, hi in rs:
        print(f"    {{0x{lo:04X}, 0x{hi:04X}}},")
    print("};")


def main() -> None:
    letters = ranges({"Lu", "Ll", "Lt", "Lm", "Lo"})
    numbers = ranges({"Nd", "Nl", "No"})
    print(f"""\
// GENERATED by gen_unicode_tables.py from Unicode {unicodedata.unidata_version} — do not edit.
//
// Sorted, non-overlapping, inclusive code point ranges for \\p{{L}} and \\p{{N}}.

#ifndef MINILLM_SRC_TOKENIZER_UNICODE_TABLES_H
#define MINILLM_SRC_TOKENIZER_UNICODE_TABLES_H

namespace minillm::unicode {{

struct CodePointRange {{
  char32_t lo;
  char32_t hi;
}};

// Lu Ll Lt Lm Lo: {len(letters)} ranges.""")
    emit("kLetter", letters)
    print(f"\n// Nd Nl No: {len(numbers)} ranges.")
    emit("kNumber", numbers)
    print("""
}  // namespace minillm::unicode

#endif  // MINILLM_SRC_TOKENIZER_UNICODE_TABLES_H""")


if __name__ == "__main__":
    main()
